SELECT
    i.ITEM_ID,
    i.DESCRIPTION,
    i.UNITS_ON_HAND,
    CASE
        WHEN i.ITEM_ID = ANY (SELECT ITEM_ID FROM INVOICE_LINE) THEN (SELECT INVOICE_NUMBER FROM INVOICE_LINE WHERE ITEM_ID = i.ITEM_ID LIMIT 1)
        ELSE NULL
    END AS INVOICE_NUMBER,
    CASE
        WHEN i.ITEM_ID = ANY (SELECT ITEM_ID FROM INVOICE_LINE) THEN (SELECT QUANTITY_ORDERED FROM INVOICE_LINE WHERE ITEM_ID = i.ITEM_ID LIMIT 1)
        ELSE NULL
    END AS QUANTITY_ORDERED
FROM
    ITEM i
ORDER BY
    i.ITEM_ID;