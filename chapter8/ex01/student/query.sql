SELECT INVOICES.INVOICE_NUM, INVOICES.CUST_ID,
 CUSTOMER.FIRST_NAME, CUSTOMER.LAST_NAME, 
 INVOICES.INVOICE_DATE,
  DATE_ADD(INVOICES.INVOICE_DATE,INTERVAL 20 DAY)
AS PROMOTION_DATE
FROM INVOICE_LINE, INVOICES, CUSTOMER 
WHERE INVOICES.INVOICE_NUM = INVOICE_LINE.INVOICE_NUM
AND INVOICES.CUST_ID = CUSTOMER.CUST_ID;
