DELIMITER //

CREATE PROCEDURE UPDATE_INVOICE (
    IN I_INVOICE_NUM CHAR(5),
    IN I_INVOICE_DATE DATE
)
BEGIN
    UPDATE INVOICES
    SET INVOICE_DATE = I_INVOICE_DATE
    WHERE INVOICE_NUM = I_INVOICE_NUM;
END //

CREATE PROCEDURE DELETE_INVOICE (
    IN I_INVOICE_NUM CHAR(5)
)
BEGIN
    DELETE FROM INVOICES
    WHERE INVOICE_NUM = I_INVOICE_NUM;
END //

DELIMITER ;
