DELIMITER //

CREATE PROCEDURE GET_CREDIT_LIMIT (
    IN I_CUST_ID INT,
    OUT I_CUSTOMER_NAME VARCHAR(255),
    OUT I_CREDIT_LIMIT DECIMAL(10, 2)
)
BEGIN
    DECLARE V_FIRST_NAME VARCHAR(100);
    DECLARE V_LAST_NAME VARCHAR(100);

    SELECT first_name, last_name, credit_limit
    INTO V_FIRST_NAME, V_LAST_NAME, I_CREDIT_LIMIT
    FROM customers
    WHERE customer_id = I_CUST_ID;

    IF FOUND_ROWS() > 0 THEN
        SET I_CUSTOMER_NAME = CONCAT(V_FIRST_NAME, ' ', V_LAST_NAME);
        SELECT CONCAT('Customer Name: ', I_CUSTOMER_NAME);
        SELECT CONCAT('Credit Limit: ', I_CREDIT_LIMIT);
    ELSE
        SELECT CONCAT('Error: Customer with ID ', I_CUST_ID, ' not found.');
    END IF;
END //

DELIMITER ;